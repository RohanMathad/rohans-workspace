const createMockEntry = (entry: Omit<LedgerEntry, "dayKey" | "monthKey" | "dateTimestamp" | "createdAt">): LedgerEntry => {
  const isBasket = entry.status === "BASKET_PLANNED";
  const timestamp = new Date(entry.date).getTime();
  return {
    ...entry,
    dayKey: entry.date,
    monthKey: isBasket ? null : entry.date.slice(0, 7),
    dateTimestamp: timestamp,
    createdAt: timestamp,
  };
};

